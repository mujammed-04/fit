/* ==========================================================================
   figures.js — собственные векторные схемы техники.
   Все иллюстрации нарисованы здесь вручную (SVG), внешние изображения
   не используются: нет вопросов с лицензиями и нет риска показать
   технику, отличающуюся от текста.

   Единый визуальный язык:
     • тёмная фигура-пиктограмма    — тело спортсмена
     • светло-серые линии            — оборудование (штанга, блок, скамья)
     • оранжевая стрелка             — направление движения
     • оранжевый пунктир             — ориентир (линия тела, уровень плеч)
   ========================================================================== */

/* ---------- примитивы ---------- */
const F = {
  svg: (vb, inner, extra = '') =>
    `<svg viewBox="${vb}" role="img" ${extra}>${inner}</svg>`,
  head: (x, y, r = 17) => `<circle class="f-head" cx="${x}" cy="${y}" r="${r}"/>`,
  neck: (x1, y1, x2, y2) =>
    `<line class="f-neck" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`,
  bar: (x1, y1, x2, y2) =>
    `<line class="f-bar" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`,
  spine: (d) => `<path class="f-spine" d="${d}"/>`,
  limb: (pts, far) => `<polyline class="f-limb${far ? ' f-far' : ''}" points="${pts}"/>`,
  gear: (d) => `<path class="f-gear" d="${d}"/>`,
  gfill: (d) => `<path class="f-gear-fill" d="${d}"/>`,
  rect: (x, y, w, h, r = 4) =>
    `<rect class="f-gear-fill" x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}"/>`,
  floor: (x1, x2, y) => `<line class="f-floor" x1="${x1}" y1="${y}" x2="${x2}" y2="${y}"/>`,
  arrow: (d) => `<path class="f-arrow" d="${d}"/>`,
  dash: (d) => `<path class="f-dash" d="${d}"/>`,
  bad: (d) => `<path class="f-badline" d="${d}"/>`,
  hand: (x, y, r = 8) => `<circle class="f-head" cx="${x}" cy="${y}" r="${r}"/>`,
  lbl: (x, y, t, a = 'middle') =>
    `<text class="f-lbl" x="${x}" y="${y}" text-anchor="${a}">${t}</text>`,
  db: (x, y, rot = 0) =>
    `<g class="f-db" transform="translate(${x},${y}) rotate(${rot})">` +
    `<rect x="-14" y="-4" width="28" height="8" rx="4"/>` +
    `<rect x="-21" y="-11" width="9" height="22" rx="4.5"/>` +
    `<rect x="12" y="-11" width="9" height="22" rx="4.5"/></g>`,
  /* стопка блинов силового блока */
  stack: (x, y, w, h) => {
    let s = `<rect class="f-gear-fill" x="${x}" y="${y}" width="${w}" height="${h}" rx="3" opacity=".55"/>`;
    for (let i = y + 11; i < y + h; i += 11) s += `<line class="f-plate" x1="${x}" y1="${i}" x2="${x + w}" y2="${i}"/>`;
    return s;
  },
  rope: (x1, y1, x2, y2) =>
    `<line class="f-cable" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`,
};

